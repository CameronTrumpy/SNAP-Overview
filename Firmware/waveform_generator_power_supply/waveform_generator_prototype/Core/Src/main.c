/* USER CODE BEGIN 0 */
void processCommand(CommandMessage *cmd, CommandResponse *resp) {

	if(cmd->code == COMMAND_SET_WAVEFORM){
		commandSetWaveform(cmd,resp);


	}else if(cmd->code >= COMMAND_PD_ALIVE && cmd->code <= COMMAND_PD_REQUEST_OUTPUT){
		parsePDCommand(&psu, cmd, resp);
	}
	else{
		// INVALID COMMAND

	    // Set response code to SUCCESS
	    resp->code = RESPONSE_INVALID;

	    // Set data length to 0
	    resp->data_len = 0;
	}
}
